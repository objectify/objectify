package com.googlecode.objectify.cmd;

import com.googlecode.objectify.Key;
import com.googlecode.objectify.Result;

import java.util.Map;


/**
 * <p>The top element in the command chain for inserting entities in the datastore.</p>
 *
 * <p>Unlike {@link Saver}, which performs an upsert, an insert fails if an entity with the same key already
 * exists. The check happens atomically on the server as part of the commit; no extra read or transaction
 * is needed.</p>
 *
 * <p>If a key already exists, the result throws a {@code DatastoreException} with reason {@code ALREADY_EXISTS}.
 * Inside a transaction, this happens when the transaction commits. Note that an automatic retry of a commit
 * that actually succeeded (e.g. after a lost response) will also produce this error.</p>
 */
public interface Inserter
{
	/**
	 * <p>Asynchronously insert a single entity in the datastore.</p>
	 *
	 * <p>If the entity has a null Long id, the value will be autogenerated and populated on the entity object
	 * when the async operation completes.  If you require this value, call now() on the result.</p>
	 *
	 * @param entity must be a registered entity type
	 * @return an asynchronous result.  To force a synchronous insert, call Result.now().
	 */
	<E> Result<Key<E>> entity(E entity);

	/**
	 * <p>Asynchronously insert a batch of entities in the datastore.</p>
	 *
	 * <p>As with {@link Saver#entities(Iterable)}, a batch is only atomic inside a transaction. Outside of a
	 * transaction, some entities may be inserted while others fail.</p>
	 *
	 * @param entities must be registered entity types
	 * @return an asynchronous result.  To force a synchronous insert, call Result.now().
	 */
	<E> Result<Map<Key<E>, E>> entities(Iterable<E> entities);

	/**
	 * A convenience method for entities(Iterable)
	 */
	<E> Result<Map<Key<E>, E>> entities(E... entities);
}
