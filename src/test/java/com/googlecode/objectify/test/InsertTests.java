package com.googlecode.objectify.test;

import com.google.cloud.datastore.DatastoreException;
import com.googlecode.objectify.Key;
import com.googlecode.objectify.test.entity.NamedTrivial;
import com.googlecode.objectify.test.entity.Trivial;
import com.googlecode.objectify.test.util.TestBase;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import static com.google.common.truth.Truth.assertThat;
import static com.googlecode.objectify.ObjectifyService.factory;
import static com.googlecode.objectify.ObjectifyService.ofy;
import static org.junit.jupiter.api.Assertions.assertThrows;

/**
 * Tests of insert(), which fails if the key already exists.
 */
class InsertTests extends TestBase {

	@Test
	void insertNewEntityWorks() {
		factory().register(NamedTrivial.class);

		final NamedTrivial triv = new NamedTrivial("foo", "bar", 5);
		final Key<NamedTrivial> k = ofy().insert().entity(triv).now();

		assertThat(k.getName()).isEqualTo("foo");

		ofy().clear();
		final NamedTrivial fetched = ofy().load().key(k).now();
		assertThat(fetched).isEqualTo(triv);
	}

	@Test
	void insertWithAutogeneratedIdWorks() {
		factory().register(Trivial.class);

		final Trivial triv = new Trivial("foo", 5);
		final Key<Trivial> k = ofy().insert().entity(triv).now();

		assertThat(triv.getId()).isNotNull();
		assertThat(k.getId()).isEqualTo(triv.getId());
	}

	@Test
	void insertExistingEntityFails() {
		factory().register(NamedTrivial.class);

		final NamedTrivial original = new NamedTrivial("foo", "original", 5);
		ofy().save().entity(original).now();

		final NamedTrivial duplicate = new NamedTrivial("foo", "duplicate", 6);
		assertThrows(DatastoreException.class, () -> ofy().insert().entity(duplicate).now());

		// Nothing was overwritten, neither in the datastore nor in the session/cache
		ofy().clear();
		final NamedTrivial fetched = ofy().load().type(NamedTrivial.class).id("foo").now();
		assertThat(fetched.getSomeString()).isEqualTo("original");
	}

	@Test
	void insertBatchInTransactionIsAllOrNothing() {
		factory().register(NamedTrivial.class);

		ofy().save().entity(new NamedTrivial("existing", "original", 1)).now();

		assertThrows(DatastoreException.class, () -> ofy().transact(() -> {
			ofy().insert().entities(
					new NamedTrivial("new", "new", 2),
					new NamedTrivial("existing", "duplicate", 3)
			).now();
		}));

		ofy().clear();
		final Map<String, NamedTrivial> fetched = ofy().load().type(NamedTrivial.class).ids("new", "existing");
		assertThat(fetched).doesNotContainKey("new");
		assertThat(fetched.get("existing").getSomeString()).isEqualTo("original");
	}

	@Test
	void insertBatchWithoutTransactionDoesNotOverwriteExisting() {
		factory().register(NamedTrivial.class);

		ofy().save().entity(new NamedTrivial("existing", "original", 1)).now();

		assertThrows(DatastoreException.class, () -> ofy().insert().entities(
				new NamedTrivial("new", "new", 2),
				new NamedTrivial("existing", "duplicate", 3)
		).now());

		// Outside a transaction the batch is not atomic, so "new" may or may not have been written
		ofy().clear();
		final NamedTrivial fetched = ofy().load().type(NamedTrivial.class).id("existing").now();
		assertThat(fetched.getSomeString()).isEqualTo("original");
	}

	@Test
	void insertExistingEntityInTransactionFailsOnCommit() {
		factory().register(NamedTrivial.class);

		ofy().save().entity(new NamedTrivial("foo", "original", 5)).now();

		assertThrows(DatastoreException.class, () -> ofy().transact(() -> {
			ofy().insert().entity(new NamedTrivial("foo", "duplicate", 6)).now();
		}));

		ofy().clear();
		final NamedTrivial fetched = ofy().load().type(NamedTrivial.class).id("foo").now();
		assertThat(fetched.getSomeString()).isEqualTo("original");
	}

	@Test
	void insertNewEntityInTransactionWorks() {
		factory().register(NamedTrivial.class);

		ofy().transact(() -> {
			ofy().insert().entity(new NamedTrivial("foo", "bar", 5)).now();
		});

		ofy().clear();
		final NamedTrivial fetched = ofy().load().type(NamedTrivial.class).id("foo").now();
		assertThat(fetched.getSomeString()).isEqualTo("bar");
	}

	@Test
	void insertingMoreThan500EntitiesWorks() {
		factory().register(NamedTrivial.class);

		final List<NamedTrivial> entities = new ArrayList<>();
		for (int i = 0; i < 501; i++)
			entities.add(new NamedTrivial("n" + i, "x", i));

		final Map<Key<NamedTrivial>, NamedTrivial> saved = ofy().insert().entities(entities).now();
		assertThat(saved).hasSize(501);
	}
}
